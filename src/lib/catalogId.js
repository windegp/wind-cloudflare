// 🔥 مصدر واحد وموحّد لتوليد Facebook Catalog ID.
//
// المشكلة التي يحلّها هذا الملف: كان هناك تطبيقان مستقلان لنفس الفكرة —
// واحد في api/fb-catalog/route.js (لتوليد g:id في XML)، وآخر ضمني في كود
// التتبّع (fbTrack calls) كان ببساطة يرسل الـ handle الخام دائماً بلا أي
// وعي باللون. النتيجتان لم تكونا متطابقتين أبداً لأي منتج بأكثر من لون
// واحد — فكانت أحداث AddToCart/Purchase لأي لون غير "الأول" لا تُطابق أي
// عنصر حقيقي في الكتالوج.
//
// هذا الملف الآن هو المصدر الوحيد لكلا الجانبين. أي تغيير مستقبلي في طريقة
// توليد الـ ID يجب أن يحدث هنا فقط.
//
// ⚠️ ملف آمن للاستيراد من السيرفر (fb-catalog/route.js) ومن الـ Client
// Components (ProductView.js, checkout/page.js, thank-you/page.js) على حد
// سواء — بدون أي استيراد لـ Node/Firebase/إلخ، فقط دوال نقية.

/**
 * يحوّل قيمة اللون الخام (كما تُخزَّن في Firestore، بنفس الحروف والمسافات
 * التي أدخلها الأدمن) إلى مفتاح ثابت وقابل للتنبؤ — نفس القيمة تماماً في كل
 * مكان يُستدعى فيه، بغض النظر عن مسافات زائدة أو اختلاف حالة الأحرف.
 *
 * .trim() أولاً — مهم: لو القيمة الخام فيها مسافة بادئة/لاحقة (خطأ إدخال
 * شائع)، فبدون trim كانت catalog تنتج "-جينز-ازرق-" (بشرطة فاضية في البداية/
 * النهاية) بينما الواجهة (اللي بتعمل trim على القيم من الأساس عبر
 * safeColors) بتنتج "جينز-ازرق" — أي عدم تطابق صامت. الآن الاثنان يستخدمان
 * نفس الدالة بالظبط، فهذا الاحتمال أصبح مستحيلاً بنيوياً.
 */
export function slugifyColor(colorValue) {
  return String(colorValue || "").trim().toLowerCase().replace(/\s+/g, "-");
}

/**
 * الدالة الوحيدة التي يجب استخدامها لتوليد أي معرّف منتج يُرسَل لـ Meta —
 * سواء في XML الكتالوج (g:id) أو في content_ids لأي حدث تتبّع.
 *
 * - منتج بدون لون (colorValue فاضي/undefined) → يرجع الـ handle الخام كما هو،
 *   بدون أي تغيير — بالضبط نفس السلوك الحالي للمنتجات بدون variants ألوان.
 * - منتج بلون محدد → `${handle}-${slugifyColor(colorValue)}` دائماً،
 *   بدون أي استثناء لـ"أول لون" — وهذا بالتحديد ما يمنع تطابق g:id مع
 *   item_group_id (الذي يبقى دائماً = handle الخام فقط).
 */
export function getCatalogId(handle, colorValue) {
  const safeHandle = String(handle || "");
  if (!colorValue) return safeHandle;
  return `${safeHandle}-${slugifyColor(colorValue)}`;
}
